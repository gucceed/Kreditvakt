// Fetches the locked HealthResponse JSON Schema artifact from norric-shared
// at the immutable tag and codegens (a) TypeScript types and (b) a Zod
// runtime validator into src/generated/. Run automatically on `npm install`
// via the postinstall hook.
//
// If the upstream tag moves (it must not for v1), or the URL changes, every
// downstream TS app's next install will pick up the new contract. The
// observability-v1.0.0-spec tag is the contract pin.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";
import { jsonSchemaToZod } from "json-schema-to-zod";

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = join(REPO_ROOT, "src", "generated");
const SOURCE_TAG = "observability-v1.1.0-spec";
const SCHEMA_URL =
  `https://raw.githubusercontent.com/gucceed/norric-shared/${SOURCE_TAG}/schemas/health-response.v1.json`;

const HEADER = `// AUTOGENERATED — DO NOT EDIT. Source: norric-shared@${SOURCE_TAG}\n// Regenerate: node scripts/generate-health-types.mjs\n\n`;

async function main() {
  process.stdout.write(`[generate-health-types] fetching ${SCHEMA_URL}\n`);
  const res = await fetch(SCHEMA_URL);
  if (!res.ok) {
    throw new Error(`fetch failed: HTTP ${res.status} ${res.statusText}`);
  }
  const schema = await res.json();

  if (schema.title !== "HealthResponse") {
    throw new Error(`unexpected schema title: ${schema.title}`);
  }

  await mkdir(OUT_DIR, { recursive: true });

  const tsTypes = await compile(schema, "HealthResponse", {
    bannerComment: "",
    additionalProperties: false,
    style: { singleQuote: false },
  });
  await writeFile(join(OUT_DIR, "health.ts"), HEADER + tsTypes);

  const zodSource = jsonSchemaToZod(schema, {
    module: "esm",
    name: "HealthResponseSchema",
    type: "HealthResponse",
  });
  await writeFile(join(OUT_DIR, "health.zod.ts"), HEADER + zodSource + "\n");

  process.stdout.write(
    `[generate-health-types] wrote src/generated/health.ts and src/generated/health.zod.ts\n`,
  );
}

main().catch((err) => {
  process.stderr.write(`[generate-health-types] FAILED: ${err.message}\n`);
  process.exit(1);
});
